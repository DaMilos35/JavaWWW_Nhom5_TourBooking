/**
 * Trả về thông tin đầy đủ của đối tác tổ chức tour dựa trên providerId hoặc providerName
 */
export function getProviderInfo(providerId, providerName) {
  if (providerId && CERTIFIED_PROVIDERS[providerId]) {
    return CERTIFIED_PROVIDERS[providerId];
  }

  if (providerName) {
    const lower = providerName.toLowerCase();
    for (const p of Object.values(CERTIFIED_PROVIDERS)) {
      if (lower.includes(p.shortName.toLowerCase()) || lower.includes(p.username.toLowerCase())) {
        return p;
      }
    }
  }

  // Mặc định trả về Du Lịch Việt (Đơn vị chủ quản)
  return CERTIFIED_PROVIDERS[4];
}
